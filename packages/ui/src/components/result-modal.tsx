import { createSignal, Show } from "solid-js"
import { Dialog as KobalteDialog } from "@kobalte/core/dialog"
import { Dialog } from "./dialog"
import { Markdown } from "./markdown"
import { AnalysisChips } from "./analysis-chips"
import { WorkflowActions, WorkflowAction } from "./workflow-actions"
import { Button } from "./button"
import { Icon } from "./icon"
import { IconButton } from "./icon-button"

export interface ResultModalProps {
    isOpen: boolean
    onOpenChange: (open: boolean) => void
    onMinimize?: () => void
    content: string
    chips?: string[]
    workflows?: WorkflowAction[]
    onChipClick?: (chip: string) => void
    onWorkflowClick?: (action: WorkflowAction) => void
}

export function ResultModal(props: ResultModalProps) {
    return (
        <KobalteDialog open={props.isOpen} onOpenChange={props.onOpenChange}>
            <KobalteDialog.Portal>
                <div class="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/50 backdrop-blur-sm animate-in fade-in">
                    <Dialog
                        class="w-full max-w-4xl h-[85vh] flex flex-col p-0 overflow-hidden shadow-2xl bg-surface-base rounded-xl"
                        title={
                            <div class="flex items-center gap-3">
                                <div class="p-2 bg-gradient-to-br from-accent-blue/20 to-accent-indigo/20 rounded-lg text-accent-blue ring-1 ring-inset ring-accent-blue/20">
                                    <Icon name="branch" class="size-5" />
                                </div>
                                <div>
                                    <h2 class="text-lg font-semibold text-text-strong leading-none">Analysis Result</h2>
                                    <p class="text-xs text-text-muted mt-1">Generated by ShopOS Agent</p>
                                </div>
                            </div>
                        }
                        action={
                            <div class="flex items-center gap-1">
                                <Show when={props.onMinimize}>
                                    <IconButton
                                        icon="collapse"
                                        variant="ghost"
                                        class="text-text-muted hover:text-text-base"
                                        onClick={() => props.onMinimize?.()}
                                        title="Minimize to chat"
                                    />
                                </Show>
                                <IconButton icon="close" variant="ghost" onClick={() => props.onOpenChange(false)} />
                            </div>
                        }
                    >
                        {/* Scrollable Content */}
                        <div class="flex-1 overflow-y-auto p-6 md:p-8 space-y-8 bg-surface-base">
                            {/* Main Result */}
                            <div class="prose prose-sm md:prose-base max-w-none text-text-base marker:text-text-muted">
                                <Markdown text={props.content} />
                            </div>

                            <div class="h-px bg-border-subtle w-full" />

                            {/* Interactive Section */}
                            <div class="space-y-8">
                                <Show when={props.chips && props.chips.length > 0}>
                                    <div class="space-y-3">
                                        <div class="flex items-center gap-2 text-xs font-semibold uppercase tracking-wider text-text-muted">
                                            <Icon name="branch" class="size-3.5" />
                                            <span>Suggested Next Steps</span>
                                        </div>
                                        <AnalysisChips chips={props.chips!} onChipClick={props.onChipClick} />
                                    </div>
                                </Show>

                                <Show when={props.workflows && props.workflows.length > 0}>
                                    <div class="space-y-3">
                                        <div class="flex items-center gap-2 text-xs font-semibold uppercase tracking-wider text-text-muted">
                                            <Icon name="workflow" class="size-3.5" />
                                            <span>Recommended Actions</span>
                                        </div>
                                        <WorkflowActions workflows={props.workflows!} onWorkflowClick={props.onWorkflowClick} />
                                    </div>
                                </Show>
                            </div>
                        </div>
                    </Dialog>
                </div>
            </KobalteDialog.Portal>
        </KobalteDialog>
    )
}
